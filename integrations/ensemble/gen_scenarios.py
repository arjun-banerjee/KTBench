"""
gen_scenarios.py — Generate Ensemble scenario files for all KTBench problems.

Usage:
    python integrations/ensemble/gen_scenarios.py \
        --problems-dir problems/ \
        --out-dir integrations/ensemble/scenarios/ \
        --model claude-opus-4-7 \
        --max-turns 30 \
        --device 0

One .py scenario file is written per problem directory found under --problems-dir.
Existing files are not overwritten unless --overwrite is passed.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

_TEMPLATE = '''\
"""
KTBench Ensemble scenario: {problem_id}
Auto-generated by gen_scenarios.py — edit freely.

Run with:
    ensemble run ktbench.{problem_id} \\
        --world ktbench \\
        --manifest integrations/ensemble \\
        --backend anthropic
"""

import os
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parent.parent.parent.parent
if str(_REPO / "integrations" / "ensemble") not in sys.path:
    sys.path.insert(0, str(_REPO / "integrations" / "ensemble"))

import ktbench_world  # noqa: F401  registers the world
from ktbench_world import PERSONAS_DIR, prompt_for_path
from ensemble import scenario
from ensemble.persona import load_persona


PROBLEM_PATH = "{problem_path}"
MAX_TURNS    = {max_turns}


def _log_agent_prompt(world, agent_id, persona_name, model):
    try:
        spec = load_persona(PERSONAS_DIR / f"{{persona_name}}.toml")
        world._native.log_note(
            f"agent_spawn: id={{agent_id}} persona={{spec.name}} model={{model}}\\n"
            f"system_prompt:\\n{{spec.system_prompt}}"
        )
    except Exception:
        pass


@scenario("ktbench.{problem_id}", world="ktbench")
async def {func_name}(world):
    os.environ["KTBENCH_PROBLEM_PATH"] = PROBLEM_PATH
    model = os.environ.get("KTBENCH_MODEL", "{model}")
    persona_name = os.environ.get("KTBENCH_PERSONA", "normal_translation")

    persona_path = PERSONAS_DIR / f"{{persona_name}}.toml"
    persona_system = ""
    if persona_path.exists():
        persona_system = load_persona(persona_path).system_prompt
    problem_prompt = prompt_for_path(PROBLEM_PATH)
    full_system = (persona_system + "\\n\\n---\\n\\n" + problem_prompt).lstrip()

    world.spawn_agent(
        id="kernel_engineer",
        model=model,
        system_prompt=full_system,
        tools=[
            "static_check",
            "compile_kernel",
            "run_correctness",
            "get_gpu_specs",
            "submit_kernel",
        ],
    )
    _log_agent_prompt(world, "kernel_engineer", persona_name, model)
    world._native.log_note(f"problem_prompt:\\n{{problem_prompt}}")

    yield world.until(world.turn_count > MAX_TURNS)

    yield {{
        "submitted":             1.0 if world.evaluate_predicate("submit_called") else 0.0,
        "submit_passed":         1.0 if world.evaluate_predicate("submit_passed") else 0.0,
        "correctness_passed":    1.0 if world.evaluate_predicate("correctness_passed") else 0.0,
        "stress_passed":         1.0 if world.evaluate_predicate("stress_passed") else 0.0,
        "sol_above_threshold":   1.0 if world.evaluate_predicate("sol_above_threshold") else 0.0,
        "static_check_failed":   1.0 if world.evaluate_predicate("static_check_failed") else 0.0,
    }}
'''


def _is_problem_dir(path: Path) -> bool:
    return (path / "meta.toml").exists() and (path / "source.py").exists()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Ensemble scenarios for KTBench problems.")
    parser.add_argument("--problems-dir", default="problems",
                        help="Directory containing problem subdirectories (default: problems)")
    parser.add_argument("--out-dir", default="integrations/ensemble/scenarios",
                        help="Output directory for generated scenario files")
    parser.add_argument("--model", default="claude-opus-4-7",
                        help="Default model for spawned agents (default: claude-opus-4-7)")
    parser.add_argument("--max-turns", type=int, default=30)
    parser.add_argument("--device", type=int, default=0)
    parser.add_argument("--overwrite", action="store_true",
                        help="Overwrite existing scenario files")
    args = parser.parse_args()

    problems_dir = Path(args.problems_dir)
    out_dir      = Path(args.out_dir)

    if not problems_dir.is_dir():
        sys.exit(f"problems-dir not found: {problems_dir}")

    out_dir.mkdir(parents=True, exist_ok=True)

    found = [p for p in sorted(problems_dir.iterdir()) if p.is_dir() and _is_problem_dir(p)]
    if not found:
        sys.exit(f"No problem directories found under {problems_dir}")

    generated = skipped = 0
    for problem_dir in found:
        problem_id = problem_dir.name
        func_name  = problem_id.replace("-", "_")
        out_file   = out_dir / f"{problem_id}.py"

        if out_file.exists() and not args.overwrite:
            print(f"  skip (exists): {out_file}")
            skipped += 1
            continue

        content = _TEMPLATE.format(
            problem_id   = problem_id,
            problem_path = str(problem_dir),
            func_name    = func_name,
            model        = args.model,
            max_turns    = args.max_turns,
            device       = args.device,
        )
        out_file.write_text(content)
        print(f"  wrote: {out_file}")
        generated += 1

    print(f"\nDone: {generated} generated, {skipped} skipped.")


if __name__ == "__main__":
    main()
