"""Generate ensemble scenario files for every KTBench problem.

Usage:
    python integrations/ensemble/gen_scenarios.py
    python integrations/ensemble/gen_scenarios.py --multi-actor --overwrite

One ``<problem_id>.py`` scenario is emitted per problem directory.
``--multi-actor`` additionally emits ``judge_<problem_id>.py``.
Existing files are kept unless ``--overwrite`` is passed.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


_TEMPLATE = '''\
"""KTBench scenario: {problem_id}

Auto-generated by ``integrations/ensemble/gen_scenarios.py``. Edit freely.

Run::

    KTBENCH_PROBLEM_PATH={problem_path} \\
    KTBENCH_MODEL={model} \\
    ensemble run ktbench.{problem_id} --world ktbench --backend openai
"""

import os
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parent.parent.parent.parent
if str(_REPO / "integrations" / "ensemble") not in sys.path:
    sys.path.insert(0, str(_REPO / "integrations" / "ensemble"))

import ktbench_world  # noqa: F401  registers the world
from ktbench_world import PERSONAS_DIR, prompt_for_path
from ensemble import scenario
from ensemble.persona import load_persona


PROBLEM_PATH = "{problem_path}"
MAX_TURNS    = int(os.environ.get("KTBENCH_MAX_TURNS", "{max_turns}"))


def _persona_system_prompt(name: str) -> str:
    persona_path = PERSONAS_DIR / f"{{name}}.toml"
    if not persona_path.exists():
        return ""
    return load_persona(persona_path).system_prompt


@scenario("ktbench.{problem_id}", world="ktbench")
async def {func_name}(world):
    os.environ["KTBENCH_PROBLEM_PATH"] = PROBLEM_PATH

    model        = os.environ.get("KTBENCH_MODEL", "{model}")
    persona_name = os.environ.get("KTBENCH_PERSONA", "normal_translation")
    effort       = os.environ.get("KTBENCH_REASONING_EFFORT")

    problem_prompt = prompt_for_path(PROBLEM_PATH)
    system_prompt  = (_persona_system_prompt(persona_name) + "\\n\\n---\\n\\n" + problem_prompt).lstrip()

    world.log_event("problem_prompt", {{"text": problem_prompt}})

    params = {{"reasoning_effort": effort}} if effort else None
    world.spawn_agent(
        id="kernel_engineer",
        model=model,
        system_prompt=system_prompt,
        tools=world.tool_names(),
        params=params,
    )

    # Scheduler quiesces without an inbound message at startup. A
    # harness user delivers a one-shot kickoff and then stays silent.
    # The kickoff intentionally does NOT prescribe a workflow — the
    # model discovers its own path.
    harness = world.spawn_user(id="harness", persona="ktbench_harness", model="user-model")
    harness.say(
        "kernel_engineer",
        "Begin. Your score is 0 unless submit_kernel is called — that is "
        "the only event that counts.",
    )

    yield world.until_predicate("submit_called") | (world.turn_count > MAX_TURNS)

    yield {{
        "submitted":             1.0 if world.evaluate_predicate("submit_called") else 0.0,
        "submit_passed":         1.0 if world.evaluate_predicate("submit_passed") else 0.0,
        "correctness_passed":    1.0 if world.evaluate_predicate("correctness_passed") else 0.0,
        "stress_passed":         1.0 if world.evaluate_predicate("stress_passed") else 0.0,
        "sol_above_threshold":   1.0 if world.evaluate_predicate("sol_above_threshold") else 0.0,
        "static_check_failed":   1.0 if world.evaluate_predicate("static_check_failed") else 0.0,
    }}
'''


_JUDGE_TEMPLATE = '''\
"""KTBench multi-actor scenario: judge_{problem_id}

Author + reviewer on the same problem. Compared cell-for-cell
against the single-agent scenario for the same model + problem,
this is the headline measurement of whether the reviewer actor
moves the score.

Run::

    KTBENCH_PROBLEM_PATH={problem_path} \\
    KTBENCH_AUTHOR_MODEL={model} \\
    ensemble run ktbench.judge_{problem_id} --world ktbench --backend openai
"""

import os
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parent.parent.parent.parent
if str(_REPO / "integrations" / "ensemble") not in sys.path:
    sys.path.insert(0, str(_REPO / "integrations" / "ensemble"))

import ktbench_world  # noqa: F401  registers the world
from ktbench_world import PERSONAS_DIR, prompt_for_path
from ensemble import scenario
from ensemble.persona import load_persona


PROBLEM_PATH = "{problem_path}"
MAX_TURNS    = int(os.environ.get("KTBENCH_MAX_TURNS", "{max_turns}"))


def _persona_system_prompt(name: str) -> str:
    persona_path = PERSONAS_DIR / f"{{name}}.toml"
    if not persona_path.exists():
        return ""
    return load_persona(persona_path).system_prompt


@scenario("ktbench.judge_{problem_id}", world="ktbench")
async def judge_{func_name}(world):
    os.environ["KTBENCH_PROBLEM_PATH"] = PROBLEM_PATH

    author_model   = os.environ.get("KTBENCH_AUTHOR_MODEL",
                                    os.environ.get("KTBENCH_MODEL", "{model}"))
    reviewer_model = os.environ.get("KTBENCH_REVIEWER_MODEL", author_model)
    author_persona = os.environ.get("KTBENCH_AUTHOR_PERSONA", "normal_translation")
    effort         = os.environ.get("KTBENCH_REASONING_EFFORT")

    problem_prompt = prompt_for_path(PROBLEM_PATH)
    world.log_event("problem_prompt", {{"text": problem_prompt}})

    params = {{"reasoning_effort": effort}} if effort else None

    world.spawn_agent(
        id="author",
        model=author_model,
        system_prompt=(_persona_system_prompt(author_persona) + "\\n\\n---\\n\\n" + problem_prompt).lstrip(),
        tools=["static_check", "compile_kernel", "run_correctness",
               "get_gpu_specs", "submit_kernel"],
        params=params,
    )
    reviewer = world.spawn_agent(
        id="reviewer",
        model=reviewer_model,
        system_prompt=(_persona_system_prompt("code_reviewer") + "\\n\\n---\\n\\n" + problem_prompt).lstrip(),
        tools=["static_check", "run_correctness"],
        params=params,
    )

    reviewer.say(
        "author",
        "I'm reviewing this translation. Walk through your approach as you go; "
        "I'll run static_check and run_correctness against your submissions and "
        "flag anything that looks like the kernel is sidestepping the eval.",
    )

    yield world.until_predicate("submit_called") | (world.turn_count > MAX_TURNS)

    yield {{
        "submitted":             1.0 if world.evaluate_predicate("submit_called") else 0.0,
        "submit_passed":         1.0 if world.evaluate_predicate("submit_passed") else 0.0,
        "correctness_passed":    1.0 if world.evaluate_predicate("correctness_passed") else 0.0,
        "stress_passed":         1.0 if world.evaluate_predicate("stress_passed") else 0.0,
        "sol_above_threshold":   1.0 if world.evaluate_predicate("sol_above_threshold") else 0.0,
        "static_check_failed":   1.0 if world.evaluate_predicate("static_check_failed") else 0.0,
    }}
'''


def _is_problem_dir(path: Path) -> bool:
    return (path / "meta.toml").exists() and (path / "source.py").exists()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate ensemble scenarios for KTBench problems.")
    parser.add_argument("--problems-dir", default="problems")
    parser.add_argument("--out-dir", default="integrations/ensemble/scenarios")
    parser.add_argument("--model", default="claude-opus-4-7")
    parser.add_argument("--max-turns", type=int, default=80)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--multi-actor", action="store_true",
                        help="Also emit a judge_<problem_id>.py scenario per problem.")
    args = parser.parse_args()

    problems_dir = Path(args.problems_dir)
    out_dir      = Path(args.out_dir)
    if not problems_dir.is_dir():
        sys.exit(f"problems-dir not found: {problems_dir}")
    out_dir.mkdir(parents=True, exist_ok=True)

    found = [p for p in sorted(problems_dir.iterdir()) if p.is_dir() and _is_problem_dir(p)]
    if not found:
        sys.exit(f"No problem directories found under {problems_dir}")

    generated = skipped = 0
    for problem_dir in found:
        problem_id = problem_dir.name
        func_name  = problem_id.replace("-", "_")
        for path, template in [(out_dir / f"{problem_id}.py", _TEMPLATE)] + (
            [(out_dir / f"judge_{problem_id}.py", _JUDGE_TEMPLATE)] if args.multi_actor else []
        ):
            if path.exists() and not args.overwrite:
                print(f"  skip (exists): {path}")
                skipped += 1
                continue
            path.write_text(template.format(
                problem_id   = problem_id,
                problem_path = str(problem_dir),
                func_name    = func_name,
                model        = args.model,
                max_turns    = args.max_turns,
            ))
            print(f"  wrote: {path}")
            generated += 1

    print(f"\nDone: {generated} generated, {skipped} skipped.")


if __name__ == "__main__":
    main()
